// Helper to get today's note based on start/wedding date
export function getNoteForDate(dateStr, customOverrides = {}) {
  // If user has a custom override for this date, return it
  if (customOverrides[dateStr]) {
    return customOverrides[dateStr];
  }

  // Calculate day index from engagement date (2026-11-20)
  const startDate = new Date("2026-11-20T00:00:00");
  const targetDate = new Date(dateStr ? dateStr + "T00:00:00" : new Date());
  
  const diffTime = targetDate - startDate;
  const diffDays = Math.max(1, Math.floor(diffTime / (1000 * 60 * 60 * 24)) + 1);

  // Find exact note or modulo pick from curated collection
  const exactNote = dailyLoveNotes.find(n => n.day === diffDays);
  if (exactNote) {
    return { ...exactNote, currentDayNumber: diffDays };
  }

  // If beyond or in-between, pick by index
  const index = (diffDays - 1) % dailyLoveNotes.length;
  const picked = dailyLoveNotes[index];
  return {
    ...picked,
    currentDayNumber: diffDays,
  };
}
